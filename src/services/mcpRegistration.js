"use strict";
// MCP registration: VS Code's MCP server definition provider and Cursor's MCP extension API (feature-detected), a
// stable launcher for external clients, and harness-specific CLI / link / native configuration installation. The extension
// native configuration edits are planned and committed by mcpConfigFiles.
const fs = require("fs");
const fsp = require("fs/promises");
const path = require("path");
const { execFile } = require("child_process");
const { clientStatus, commitClientInstall, prepareClientInstall, prepareClientUninstall } = require("./mcpConfigFiles");

const PROVIDER_ID = "emberprobe";
const {
    CLIENTS,
    CLI_CLIENTS,
    SERVER_NAME,
    configSnippet,
    cursorInstallLink,
    installArgs
} = require("./mcpClientConfig");
const CLI_TIMEOUT_MS = 30000;
const ERROR_TAIL = 300;
// The buttons each client state offers in the sidebar card. A file that cannot be read can only be merged by hand.
const STATE_ACTIONS = Object.freeze({
    notInstalled: ["install"],
    installed: ["uninstall"],
    outdated: ["upgrade", "uninstall"],
    invalid: ["copy"],
    manual: ["copy"],
    builtin: []
});
const CLIENT_ACTIONS = new Set(Object.values(STATE_ACTIONS).flat());

// The launcher path is stable (globalStorage/mcp); its content is rewritten on every activation to the current
// extension install path.
function launcherSource(serverPath) {
    return [
        "// Generated by EmberProbe on activation; points at the installed extension's MCP server.",
        '"use strict";',
        `require(${JSON.stringify(serverPath)})`,
        "    .main()",
        "    .catch((error) => {",
        "        process.stderr.write(`EmberProbe MCP server failed: ${(error && error.stack) || error}\\n`);",
        "        process.exit(1);",
        "    });",
        ""
    ].join("\n");
}

// Command-line fragments: Windows paths never contain double quotes; POSIX uses single quotes so $, ` and friends are
// not expanded by the shell.
function shellQuote(value, platform = process.platform) {
    return platform === "win32" ? `"${value}"` : `'${String(value).replace(/'/g, "'\\''")}'`;
}

// POSIX wrapper script: starts the MCP server with the editor's own runtime instead of node on PATH. Runtime paths of
// remote servers include a commit and disappear after upgrades, so the script is rewritten on every activation and
// falls back to node on PATH only when the runtime is gone.
function wrapperSource(runtime, launcher) {
    return [
        "#!/bin/sh",
        "# Generated by EmberProbe on activation; starts the MCP server with the editor's bundled runtime.",
        `runtime=${shellQuote(runtime, "linux")}`,
        `launcher=${shellQuote(launcher, "linux")}`,
        'if [ -x "$runtime" ]; then ELECTRON_RUN_AS_NODE=1 exec "$runtime" "$launcher" "$@"; fi',
        'exec node "$launcher" "$@"',
        ""
    ].join("\n");
}

/**
 * Launch command for external clients, using absolute paths. Windows runs the editor's Electron directly (the exe in
 * the install root, stable across upgrades) with ELECTRON_RUN_AS_NODE; POSIX goes through the wrapper script. The
 * variable is omitted when toolsets is empty (the default toolset).
 * @param {{ platform: string, runtime: string, launcher: string, wrapper: string, toolsets?: string }} options
 * @returns {{ command: string, args: string[], env: Record<string, string> }}
 */
function serverCommand({ platform, runtime, launcher, wrapper, toolsets }) {
    const env = toolsets ? { EMBERPROBE_MCP_TOOLSETS: toolsets } : {};
    if (platform === "win32") return { command: runtime, args: [launcher], env: { ELECTRON_RUN_AS_NODE: "1", ...env } };
    return { command: wrapper, args: [], env };
}

function displayArg(value, platform) {
    return /^[\w@%+=:,./\\-]+$/.test(value) ? value : shellQuote(value, platform);
}

/**
 * Finds an executable on PATH. Windows accepts only .exe/.cmd/.bat (npm installs .cmd wrappers, native installs .exe).
 * @param {string} name
 * @param {NodeJS.ProcessEnv} [env]
 * @param {string} [platform]
 * @returns {string} absolute path, or an empty string when not found
 */
function findExecutable(name, env = process.env, platform = process.platform) {
    const pathKey = Object.keys(env).find((key) => key.toUpperCase() === "PATH") || "PATH";
    const dirs = String(env[pathKey] || "")
        .split(platform === "win32" ? ";" : ":")
        .filter(Boolean);
    const names = platform === "win32" ? [".exe", ".cmd", ".bat"].map((ext) => name + ext) : [name];
    const join = platform === "win32" ? path.win32.join : path.posix.join;
    for (const dir of dirs)
        for (const candidate of names) {
            const file = join(dir.replace(/^"(.*)"$/, "$1"), candidate);
            try {
                if (!fs.statSync(file).isFile()) continue;
                if (platform !== "win32") fs.accessSync(file, fs.constants.X_OK);
                return file;
            } catch {
                /* try the next candidate */
            }
        }
    return "";
}

// .cmd/.bat can only start through cmd.exe. Every argument is double-quoted; arguments containing ", %, ! or line
// breaks cannot pass safely through cmd, so null is returned.
function cmdLine(file, args) {
    const parts = [file, ...args];
    if (parts.some((part) => /["%!\r\n]/.test(part))) return null;
    return parts.map((part) => `"${part}"`).join(" ");
}

/**
 * Runs a client CLI without a shell (except .cmd/.bat).
 * @returns {Promise<{ ok: boolean, stdout: string, stderr: string, error?: string }>}
 */
function runCli(file, args, options = {}) {
    const platform = options.platform || process.platform;
    const run = options.execFile || execFile;
    const env = options.env || process.env;
    const runOptions = { timeout: CLI_TIMEOUT_MS, windowsHide: true, env };
    let command = file;
    let commandArgs = args;
    if (platform === "win32" && /\.(cmd|bat)$/i.test(file)) {
        const line = cmdLine(file, args);
        if (!line) return Promise.resolve({ ok: false, stdout: "", stderr: "", error: "UNSAFE_ARGUMENT" });
        command = env.ComSpec || env.COMSPEC || "cmd.exe";
        commandArgs = ["/d", "/s", "/c", `"${line}"`];
        Object.assign(runOptions, { windowsVerbatimArguments: true });
    }
    return new Promise((resolve) => {
        run(command, commandArgs, runOptions, (error, stdout, stderr) => {
            const result = { ok: !error, stdout: String(stdout || ""), stderr: String(stderr || "") };
            if (error) result.error = String(error.code || error.message);
            resolve(result);
        });
    });
}

function errorTail(result) {
    const text = (result.stderr || result.stdout || result.error || "").trim();
    return text.length > ERROR_TAIL ? `…${text.slice(-ERROR_TAIL)}` : text;
}

class McpRegistration {
    /**
     * @param {{
     *   vscode: any, context: any, t: (key: string, params?: Record<string, any>) => string,
     *   isAvailable: () => boolean, isEnabled?: () => boolean, instanceId: () => string, toolsets: () => string,
     *   onResolve: () => Promise<void>, onConfigured?: () => void, post?: (message: any) => void,
     *   platform?: string, runtime?: string, findExecutable?: (name: string) => string,
     *   runCli?: (file: string, args: string[]) => ReturnType<typeof runCli>,
     *   prepareInstall?: (client: string, snippet: string) => Promise<any>,
     *   prepareUninstall?: (client: string) => Promise<any>,
     *   commitInstall?: (plan: any) => Promise<any>,
     *   readStatus?: (client: string, snippet: string) => ReturnType<typeof clientStatus>
     * }} options
     */
    constructor(options) {
        this.vscode = options.vscode;
        this.context = options.context;
        this.t = options.t;
        this.isAvailable = options.isAvailable;
        this.isEnabled = options.isEnabled || options.isAvailable;
        this.instanceId = options.instanceId;
        this.toolsets = options.toolsets;
        this.onResolve = options.onResolve;
        this.onConfigured = options.onConfigured || (() => {});
        this.post = options.post || (() => {});
        this.platform = options.platform || process.platform;
        this.runtime = options.runtime || process.execPath;
        this.findExecutable = options.findExecutable || ((name) => findExecutable(name, process.env, this.platform));
        this.runCli = options.runCli || ((file, args) => runCli(file, args, { platform: this.platform }));
        this.prepareInstall = options.prepareInstall || prepareClientInstall;
        this.prepareUninstall = options.prepareUninstall || prepareClientUninstall;
        this.commitInstall = options.commitInstall || commitClientInstall;
        this.readStatus = options.readStatus || clientStatus;
        this.busyClient = "";
        this.emitter = null;
        this.registered = false;
        this.host = "";
        this.cursorServer = "";
    }

    serverPath() {
        return path.join(this.context.extensionPath, "dist", "mcp-server.js");
    }

    launcherPath() {
        return path.join(this.context.globalStorageUri.fsPath, "mcp", "emberprobe-mcp.js");
    }

    wrapperPath() {
        return path.join(this.context.globalStorageUri.fsPath, "mcp", "emberprobe-mcp");
    }

    async writeLauncher() {
        const file = this.launcherPath();
        await fsp.mkdir(path.dirname(file), { recursive: true });
        await fsp.writeFile(file, launcherSource(this.serverPath()));
        if (this.platform !== "win32") {
            await fsp.writeFile(this.wrapperPath(), wrapperSource(this.runtime, file));
            await fsp.chmod(this.wrapperPath(), 0o755);
        }
        return file;
    }

    // Launch command for external clients (call writeLauncher first).
    serverSpec() {
        return serverCommand({
            platform: this.platform,
            runtime: this.runtime,
            launcher: this.launcherPath(),
            wrapper: this.wrapperPath(),
            toolsets: this.toolsets()
        });
    }

    // In remote windows the server path belongs to the remote host while Cursor starts MCP servers locally, so Cursor
    // registration and links are not offered remotely.
    isRemote() {
        return !!this.vscode.env?.remoteName;
    }

    cursorApi() {
        const mcp = this.vscode.cursor?.mcp;
        return typeof mcp?.registerServer === "function" && typeof mcp?.unregisterServer === "function" ? mcp : null;
    }

    // Prefers Cursor's MCP extension API; otherwise registers the provider on VS Code builds with the MCP API, skipping
    // older versions quietly. Returns whether anything was registered.
    register() {
        if (this.cursorApi() && !this.isRemote()) {
            this.host = "cursor";
            this.registered = true;
            this.syncCursor();
            return true;
        }
        const lm = this.vscode.lm;
        if (typeof lm?.registerMcpServerDefinitionProvider !== "function" || !this.vscode.McpStdioServerDefinition)
            return false;
        this.emitter = new this.vscode.EventEmitter();
        const provider = {
            onDidChangeMcpServerDefinitions: this.emitter.event,
            provideMcpServerDefinitions: () => this.definitions(),
            resolveMcpServerDefinition: async (definition) => {
                // VS Code resolves the definition only after the user accepts the MCP trust prompt; start the Bridge
                // for this window then.
                if (!this.isAvailable()) return undefined;
                await this.onResolve();
                return definition;
            }
        };
        this.context.subscriptions.push(lm.registerMcpServerDefinitionProvider(PROVIDER_ID, provider), this.emitter);
        this.host = "vscode";
        this.registered = true;
        return true;
    }

    serverEnv() {
        const env = { ELECTRON_RUN_AS_NODE: "1" };
        const toolsets = this.toolsets();
        if (toolsets) env.EMBERPROBE_MCP_TOOLSETS = toolsets;
        return env;
    }

    definitions() {
        if (!this.isAvailable()) return [];
        const env = { ...this.serverEnv(), EMBERPROBE_BRIDGE_INSTANCE: this.instanceId() };
        const version = this.context.extension?.packageJSON?.version;
        return [
            new this.vscode.McpStdioServerDefinition("EmberProbe", process.execPath, [this.serverPath()], env, version)
        ];
    }

    // Cursor has neither VS Code's trust prompt nor a resolve callback, so it is registered only while Agent access is
    // enabled, and registration itself does not start the Bridge. Registration is not bound to a window: the server
    // locates the Bridge by MCP roots or working directory, and every window registers the same content.
    syncCursor() {
        const api = this.host === "cursor" ? this.cursorApi() : null;
        if (!api) return;
        const server = this.isEnabled()
            ? { command: this.runtime, args: [this.serverPath()], env: this.serverEnv() }
            : null;
        const key = server ? JSON.stringify(server) : "";
        if (key === this.cursorServer) return;
        try {
            if (this.cursorServer) api.unregisterServer(SERVER_NAME);
            if (server) api.registerServer({ name: SERVER_NAME, server });
            this.cursorServer = key;
        } catch (error) {
            this.cursorServer = "";
            console.warn("Cursor MCP registration:", error.message);
        }
    }

    changed() {
        this.emitter?.fire();
        this.syncCursor();
    }

    clients() {
        return CLIENTS.filter((client) => client !== "cursor" || (this.host !== "cursor" && !this.isRemote()));
    }

    async readClient(client, spec) {
        if (client === "json") return { client, state: "manual", actions: STATE_ACTIONS.manual, files: [] };
        try {
            // Cursor's snippet is an install link; its file holds the plain mcpServers shape.
            const snippet = configSnippet(client === "cursor" ? "json" : client, spec);
            const status = await this.readStatus(client, snippet);
            return { client, ...status, actions: STATE_ACTIONS[status.state] };
        } catch (error) {
            // Cursor merges its own file from the install link, so that stays available.
            const actions = client === "cursor" ? ["install"] : STATE_ACTIONS.invalid;
            return { client, state: "invalid", actions, files: [], error: errorTail({ error: error.message }) };
        }
    }

    // The sidebar card's view of every client. Copilot uses the server VS Code gets from the provider, so it has nothing
    // to install; Cursor's own row is absent inside Cursor for the same reason.
    async clientStatuses(error) {
        const spec = this.serverSpec();
        const builtin = { client: "copilot", state: "builtin", actions: STATE_ACTIONS.builtin, files: [] };
        return {
            type: "mcpClients",
            clients: [
                ...(this.host === "vscode" ? [builtin] : []),
                ...(await Promise.all(this.clients().map((client) => this.readClient(client, spec))))
            ],
            busy: this.busyClient,
            ...(error ? { error } : {})
        };
    }

    async publishClients() {
        try {
            this.post(await this.clientStatuses());
        } catch (error) {
            console.warn("MCP client status:", error.message);
        }
    }

    pick(client) {
        const executable = CLI_CLIENTS[client] ? this.findExecutable(CLI_CLIENTS[client]) : "";
        const description =
            client === "cursor" || client === "json" ? this.t(`mcp.method.${client}`) : this.t("mcp.method.native");
        return { label: this.t(`mcp.client.${client}`), description, client, executable };
    }

    // Every named external client has a native file adapter, except Cursor which uses its own install API/link.
    // User configuration is never changed on activation: this command previews the files, and the sidebar writes when
    // its button is pressed.
    async installClient() {
        const picks = this.clients().map((client) => this.pick(client));
        const choice = await this.vscode.window.showQuickPick(picks, { placeHolder: this.t("mcp.pickClient") });
        if (!choice) return null;
        const result = await this.install(choice);
        await this.publishClients();
        return result;
    }

    // One sidebar action on one client. The button already names the client and the action, so installing and upgrading
    // write at once; removing still asks. A CLI's `mcp add` refuses a name that already exists, so the file is merged.
    async runClientAction(client, action) {
        if (!this.clients().includes(client) || !CLIENT_ACTIONS.has(action))
            throw Object.assign(new Error("Unknown MCP client action"), { code: "INVALID_PARAMS" });
        if (this.busyClient)
            throw Object.assign(new Error("Another MCP client is being changed"), { code: "MCP_BUSY" });
        this.busyClient = client;
        try {
            const choice = this.pick(client);
            if (action === "uninstall") return await this.uninstall(choice);
            if (action === "copy") return await this.copy(choice);
            return await this.install({ ...choice, executable: "", direct: true });
        } finally {
            this.busyClient = "";
        }
    }

    async copy(choice) {
        await this.writeLauncher();
        await this.vscode.env.clipboard.writeText(configSnippet(choice.client, this.serverSpec()));
        this.onConfigured();
        const key = choice.client === "json" ? "mcp.configCopied" : `mcp.configCopied.${choice.client}`;
        this.vscode.window.showInformationMessage(this.t(key, { client: choice.label }));
        return { client: choice.client, method: "clipboard" };
    }

    async uninstall(choice) {
        const window = this.vscode.window;
        const plan = await this.prepareUninstall(choice.client);
        const remove = this.t("mcp.uninstall");
        const answer = await window.showWarningMessage(
            this.t("mcp.uninstallConfirm", { client: choice.label }),
            { modal: true, detail: plan.files.map((entry) => entry.file).join("\n") },
            remove
        );
        if (answer !== remove) return null;
        const result = await this.commitInstall(plan);
        window.showInformationMessage(this.t("mcp.uninstalled", { client: choice.label }));
        return { client: choice.client, method: "file", ok: true, files: result.files };
    }

    async install(choice) {
        const window = this.vscode.window;
        await this.writeLauncher();
        const spec = this.serverSpec();
        const snippet = configSnippet(choice.client, spec);
        const label = choice.label;
        if (choice.client === "cursor") {
            const opened = await this.vscode.env.openExternal(this.vscode.Uri.parse(snippet));
            if (!opened) {
                await this.vscode.env.clipboard.writeText(snippet);
                window.showWarningMessage(this.t("mcp.cursorLinkCopied"));
                return { client: choice.client, method: "clipboard", snippet };
            }
            this.onConfigured();
            window.showInformationMessage(this.t("mcp.cursorOpened"));
            return { client: choice.client, method: "link", snippet };
        }
        if (choice.client === "json") {
            await this.vscode.env.clipboard.writeText(snippet);
            this.onConfigured();
            window.showInformationMessage(this.t("mcp.configCopied", { client: label }));
            return { client: choice.client, method: "clipboard", snippet };
        }
        return this.installNative(choice, spec, snippet);
    }

    async installNative(choice, spec, snippet) {
        const window = this.vscode.window;
        let plan;
        try {
            plan = await this.prepareInstall(choice.client, snippet);
        } catch (error) {
            return this.installFailure(choice, snippet, "file", error.message);
        }
        const install = this.t("mcp.install");
        const copy = this.t("mcp.copyConfig");
        const useCli = this.t("mcp.useCli");
        const command = choice.executable
            ? [CLI_CLIENTS[choice.client], ...installArgs(choice.client, spec)]
                  .map((arg) => displayArg(arg, this.platform))
                  .join(" ")
            : "";
        const detail = `${plan.files.map((entry) => entry.file).join("\n")}\n\n${snippet}${command ? `\n\nCLI: ${command}` : ""}`;
        const answer = choice.direct
            ? install
            : await window.showInformationMessage(
                  this.t("mcp.nativeConfirm", { client: choice.label }),
                  { modal: true, detail },
                  install,
                  ...(choice.executable ? [useCli] : []),
                  copy
              );
        if (answer === copy) {
            await this.vscode.env.clipboard.writeText(snippet);
            this.onConfigured();
            window.showInformationMessage(this.t(`mcp.configCopied.${choice.client}`));
            return { client: choice.client, method: "clipboard", snippet };
        }
        if (answer === useCli && choice.executable) {
            const result = await this.runCli(choice.executable, installArgs(choice.client, spec));
            if (!result.ok) return this.installFailure(choice, snippet, "cli", errorTail(result));
            this.onConfigured();
            window.showInformationMessage(this.t("mcp.installed", { client: choice.label }));
            return { client: choice.client, method: "cli", ok: true, snippet };
        }
        if (answer !== install) return null;
        let result;
        try {
            result = await this.commitInstall(plan);
        } catch (error) {
            return this.installFailure(choice, snippet, "file", error.message);
        }
        this.onConfigured();
        window.showInformationMessage(
            this.t("mcp.nativeInstalled", { client: choice.label, files: result.files.join(", ") })
        );
        return { client: choice.client, method: "file", ok: true, files: result.files, snippet };
    }

    async installFailure(choice, snippet, method, error) {
        await this.vscode.env.clipboard.writeText(snippet);
        this.vscode.window.showErrorMessage(
            this.t("mcp.installFailed", {
                client: choice.label,
                error: errorTail({ error }),
                instructions: this.t(`mcp.configCopied.${choice.client}`)
            })
        );
        return { client: choice.client, method, ok: false, snippet };
    }
}

module.exports = {
    McpRegistration,
    configSnippet,
    cursorInstallLink,
    findExecutable,
    installArgs,
    launcherSource,
    runCli,
    serverCommand,
    wrapperSource,
    PROVIDER_ID,
    CLIENTS
};
